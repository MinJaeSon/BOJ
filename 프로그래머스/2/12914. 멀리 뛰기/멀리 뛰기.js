function solution(n) {
    const d = Array(n + 1).fill(0);
    
    d[1] = 1; // 1
    d[2] = 2; // 1 1 / 2
    // 3 -> 1 1 1 / 1 2 / 2 1
    // 5 -> 1 1 1 1 / 1 1 2 / 1 2 1 / 2 1 1 / 2 2
    // 8 -> 1 1 1 1 1 / 2 2 1 / 2 1 2 / 1 2 2 / 2 1 1 1 / 1 2 1 1 / 1 1 2 1 / 1 1 1 2
    
    for (let i = 3; i <= n; i++) {
        d[i] = (d[i - 1] + d[i - 2]) % 1234567;
    }
    
    return d[n];
}